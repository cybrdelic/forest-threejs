"""Integrate the supported correlated GGX model's directional reflectance."""
from pathlib import Path
import numpy as np
root=Path(__file__).resolve().parents[2]
count=16384
idx=np.arange(count,dtype=float)
y=(idx+.5)/count
phi=idx*2.399963229728653
rad=np.sqrt(1-y*y)
x=rad*np.cos(phi);z=rad*np.sin(phi)
rows=[]
for roughness in np.linspace(.42,1,16):
    alpha2=roughness**4
    row=[]
    for noV in np.linspace(0,1,32):
        nv=max(noV,.001)
        vx=np.sqrt(1-nv*nv)
        hx=x+vx;hy=y+nv;hz=z.copy()
        inv=1/np.sqrt(hx*hx+hy*hy+hz*hz)
        hx*=inv;hy*=inv;hz*=inv
        noH=hy
        loH=np.maximum(0,x*hx+y*hy+z*hz)
        denominator=1+noH*noH*(alpha2-1)
        distribution=alpha2/(np.pi*denominator*denominator)
        visibility=.5/np.maximum(.00001,y*np.sqrt(nv*nv*(1-alpha2)+alpha2)+nv*np.sqrt(y*y*(1-alpha2)+alpha2))
        fresnel=.04+.96*(1-loH)**5
        energy=np.mean(2*np.pi*distribution*visibility*fresnel*y)
        row.append(float(energy))
    rows.extend(row)
values=',\n '.join(','.join(f'{x:.7f}' for x in rows[i:i+8]) for i in range(0,len(rows),8))
js='''// Correlated GGX/Smith dielectric directional reflectance, F0=.04.
// 16 roughness levels (.42–1) × 32 view cosines (0–1).
// Generated by tools/lighting/build-dielectric-dfg.py using 16,384 equal-area
// incoming directions at every texel. This is the integral of our direct lobe.
export const dielectricDFG = [
 '''+values+'''\n];
'''
(root/'dist/dielectric-dfg.js').write_text(js)
print('Integrated',len(rows),'directional reflectance samples')
