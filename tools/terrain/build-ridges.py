"""Prepare the measured outer landform. Source coordinates are Web Mercator pixels."""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from urllib.request import urlopen
from io import BytesIO
import argparse
import base64
import hashlib
import json
import math
import numpy as np
from PIL import Image
from scipy.ndimage import map_coordinates

root = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser()
parser.add_argument('--cache', type=Path)
args = parser.parse_args()
# Match the opening meadow's sight line to a corridor in the Smoky Mountains.
zoom = 12
station = ((547*256+240.91562183491317+.5)*2-.5, (806*256+399.67264417821474+.5)*2-.5)
lat = math.degrees(math.atan(math.sinh(math.pi * (1-2*(station[1]+.5)/(256*2**zoom)))))
lon = 360*(station[0]+.5)/(256*2**zoom)-180
step = 40075016.6856*math.cos(math.radians(lat))/(256*2**zoom)
axis = np.linspace(-6500,6500,401)
z,x = np.meshgrid(axis,axis,indexing='ij')
# Rotate relative to the scene's +X/-Z compass. Preserve the reference
# meadow, drainage and planted groves in the inner terrain.
yaw = 0.2323316064-math.atan2(260,1110)
dx,dz=x+170,z-210
cols=station[0]+(dx*math.cos(yaw)-dz*math.sin(yaw))/step
rows=station[1]+(dx*math.sin(yaw)+dz*math.cos(yaw))/step
x0,x1=int((cols.min()-1)//256),int((cols.max()+1)//256)
y0,y1=int((rows.min()-1)//256),int((rows.max()+1)//256)
def download(key):
    tx,ty=key
    path=args.cache/f'{zoom}-{tx}-{ty}.png' if args.cache else None
    url=f'https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{zoom}/{tx}/{ty}.png'
    if path and path.is_file():
        data=path.read_bytes()
    else:
        with urlopen(url,timeout=35) as response:
            data=response.read()
        if path:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(data)
    tile=np.asarray(Image.open(BytesIO(data))).astype(float)
    heights=tile[...,0]*256+tile[...,1]+tile[...,2]/256-32768
    return key,heights,{'url':url,'sha256':hashlib.sha256(data).hexdigest()}
keys=[(tx,ty) for ty in range(y0,y1+1) for tx in range(x0,x1+1)]
mosaic=np.zeros(((y1-y0+1)*256,(x1-x0+1)*256))
sources=[]
with ThreadPoolExecutor(max_workers=6) as pool:
    for (tx,ty),h,credit in pool.map(download,keys):
        yy,xx=(ty-y0)*256,(tx-x0)*256
        mosaic[yy:yy+256,xx:xx+256]=h
        sources.append(credit)
height=map_coordinates(mosaic,[rows-y0*256,cols-x0*256],order=1)
# Map measured relief to the scene datum, retaining valleys and slope aspect.
height=245.0+.7374267642*height-677.54165677
quantized=np.rint(height*2).astype('<i2')
delta=np.diff(quantized,axis=1,prepend=np.zeros((401,1),dtype='<i2')).astype('<i2')
encoded=base64.b64encode(delta.tobytes()).decode('ascii')
asset=root/'dist/assets/outer-ridges.js'
asset.write_text(
    '// Delta-coded signed half-metre elevations. Generated by tools/terrain/build-ridges.py.\n'
    +'const raw=atob("'+encoded+'");\n'
    +"""const heights = new Int16Array(401*401);
for (let row=0;row<401;row++) {
  let value=0;
  for (let col=0;col<401;col++) {
    const i=row*401+col;
    const word=raw.charCodeAt(2*i) | raw.charCodeAt(2*i+1)<<8;
    value+=(word<<16)>>16;
    heights[i]=value;
  }
}
export function measuredRidge(x,z) {
  const u=Math.min(399.99999,Math.max(0,(x+6500)/32.5));
  const v=Math.min(399.99999,Math.max(0,(z+6500)/32.5));
  const i=Math.floor(v)*401+Math.floor(u);
  const s=u-Math.floor(u),t=v-Math.floor(v);
  const a=heights[i]*(1-s)+heights[i+1]*s;
  const b=heights[i+401]*(1-s)+heights[i+402]*s;
  return .5*(a*(1-t)+b*t);
}
""")
metadata={'dataset':'Mapzen Terrain Tiles','attribution':'Mapzen, U.S. Geological Survey and other elevation contributors. See the dataset attribution list.','registry':'https://registry.opendata.aws/terrain-tiles/','attribution_url':'https://github.com/tilezen/joerd/blob/master/docs/attribution.md','source_camera_latitude':lat,'source_camera_longitude':lon,'vertical_scale':.7374267642,'output_spacing_metres':32.5,'sources':sources}
(root/'dist/assets/outer-ridges.json').write_text(json.dumps(metadata,indent=2)+'\n')
print(f'Wrote {len(sources)} tiles at {lat:.4f},{lon:.4f}, relief {height.min():.0f}–{height.max():.0f} scene metres')
